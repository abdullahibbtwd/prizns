/**
 * Repair mid-word truncated article slugs and emit nginx 301 redirects.
 *
 *   npm run repair:slugs --prefix api -- --dry-run
 *   npm run repair:slugs --prefix api
 *
 * Writes extra lines to deploy/nginx/slug-redirects.map (merged by ops / nginx).
 */
import { config as loadEnv } from 'dotenv';
import { appendFile, mkdir, readFile, writeFile } from 'fs/promises';
import { dirname, resolve } from 'path';
import { PrismaClient } from '@prisma/client';
import { PrismaPg } from '@prisma/adapter-pg';
import { ConfigService } from '@nestjs/config';
import { buildArticlePath } from '../articles/section.util';
import { ensureUniqueSlug, slugify } from '../common/slug.util';
import { looksMidWordTruncated } from './slug-truncation';

loadEnv({ path: resolve(__dirname, '../../../.env') });
loadEnv({ path: resolve(__dirname, '../../.env') });

const dryRun = process.argv.includes('--dry-run');
const OUT = resolve(
  __dirname,
  '../../../deploy/nginx/slug-redirects.map',
);

function formatMapLine(from: string, to: string) {
  return `${from} ${to};`;
}

async function main() {
  const connectionString =
    process.env.DATABASE_URL ||
    new ConfigService().get<string>('DATABASE_URL');
  if (!connectionString) throw new Error('DATABASE_URL is required');

  const adapter = new PrismaPg({ connectionString });
  const prisma = new PrismaClient({ adapter });
  const redirects: Array<{ from: string; to: string }> = [];

  try {
    const articles = await prisma.article.findMany({
      select: {
        id: true,
        slug: true,
        path: true,
        section: true,
        titleBg: true,
      },
      orderBy: { createdAt: 'asc' },
    });

    for (const article of articles) {
      const ideal = slugify(article.titleBg);
      if (!looksMidWordTruncated(article.slug, ideal)) continue;

      const nextSlug = await ensureUniqueSlug(
        article.titleBg,
        async (candidate) => {
          if (candidate === article.slug) return false;
          const found = await prisma.article.findFirst({
            where: {
              section: article.section,
              slug: candidate,
              NOT: { id: article.id },
            },
            select: { id: true },
          });
          return Boolean(found);
        },
      );
      if (nextSlug === article.slug) continue;

      const nextPath = buildArticlePath(article.section, nextSlug);
      console.log(
        `${dryRun ? '[dry-run] ' : ''}${article.path} → ${nextPath}`,
      );

      redirects.push(
        { from: article.path, to: nextPath },
        { from: `${article.path}/`, to: nextPath },
        { from: `/en${article.path}`, to: `/en${nextPath}` },
        { from: `/en${article.path}/`, to: `/en${nextPath}` },
      );

      if (!dryRun) {
        await prisma.article.update({
          where: { id: article.id },
          data: { slug: nextSlug, path: nextPath },
        });
      }
    }

    if (redirects.length === 0) {
      console.log('No mid-word truncated slugs found.');
      return;
    }

    const header = [
      '# Auto-generated by api/src/wordpress-import/repair-slugs.ts',
      '# Include from nginx: include /path/to/slug-redirects.map;',
      '',
    ];
    const lines = redirects.map(({ from, to }) => formatMapLine(from, to));

    if (dryRun) {
      console.log(`Would write ${lines.length} redirect line(s) to ${OUT}`);
      return;
    }

    await mkdir(dirname(OUT), { recursive: true });
    let existing = '';
    try {
      existing = await readFile(OUT, 'utf8');
    } catch {
      // create new
    }
    const existingSet = new Set(
      existing
        .split('\n')
        .map((line) => line.trim())
        .filter((line) => line && !line.startsWith('#')),
    );
    const fresh = lines.filter((line) => !existingSet.has(line));
    if (!existing.trim()) {
      await writeFile(OUT, `${header.join('\n')}${fresh.join('\n')}\n`, 'utf8');
    } else if (fresh.length) {
      await appendFile(OUT, `${fresh.join('\n')}\n`, 'utf8');
    }
    console.log(`Wrote ${fresh.length} redirect(s) to ${OUT}`);
  } finally {
    await prisma.$disconnect();
  }
}

if (require.main === module) {
  main().catch((err) => {
    console.error(err);
    process.exit(1);
  });
}
